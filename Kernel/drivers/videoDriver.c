// Cursor helpers internos
static int cursor_pixel_height() {
    // Igual al alto de los caracteres
    int h = fontHeight * font_size;
    int maxH = get_screen_height() - cursor_y;
    if (h > maxH) h = maxH;
    return h;
}

static int cursor_pixel_width() {
    // Un poco menos ancho que un carácter (mitad de la celda)
    int w = fontWidth / 2;
    if (w < 1) w = 1;
    int maxW = get_screen_width() - cursor_x;
    if (w > maxW) w = maxW;
    return w;
}

static void erase_cursor() {
    if (!cursor_visible) return;
    draw_filled_box(cursor_x, cursor_y, cursor_pixel_width(), cursor_pixel_height(), 0x000000);
}

void draw_char(char c, uint32_t color) {
    // Borrar cursor previo antes de dibujar el carácter
    erase_cursor();

    if(c=='\b') {
        x -= fontWidth;
        if(x < 0 && lines > 0) {
            y -= fontHeight * font_size;
            x = get_screen_width() - fontWidth;
        }
        delete_char();
        update_cursor_position(x, y);
        draw_cursor();
        return;
    }
    else if(c=='\n') {
        new_line();
        update_cursor_position(x, y);
        draw_cursor();
        return;
    }
    if (c < 0 || c >= 128) return;

    const uint8_t *glyph = font8x8_basic[(int)c];
    int scale = fontWidth / 8;

    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            if (glyph[row] & (1 << col)) {
                for (int dy = 0; dy < scale; dy++) {
                    for (int dx = 0; dx < scale; dx++) {
                        putPixel(color, x + col * scale + dx, y + row * scale + dy);
                    }
                }
            }
        }
    }
    x += fontWidth;    
    if (x >= get_screen_width()) {
        x = 0;
        y += fontHeight * font_size; 
        lines++;
    if (y + fontHeight > get_screen_height()) {
            scroll_screen(0x000000); 
            y -= fontHeight * font_size * SCROLL_LINES;
            if (y < 0) y = 0;
        }
    }
    // Dibujar cursor en la nueva posición
    update_cursor_position(x, y);
    draw_cursor();
}

void delete_char(void){
    if(lines == 0 && x < fontWidth * 3){
        return; // Si no se bajaron lineas, no se puede borrar hasta el area del prompt
    }

    for (int row = 0; row < fontWidth; row++) {
        for (int col = 0; col < fontHeight; col++) {
            putPixel(0x000000, x + col, y + row); 
        }
    }
}

void clear_framebuffer(uint32_t color) {
    uint8_t * framebuffer = (uint8_t *) VBE_mode_info->framebuffer;
    int width = get_screen_width();
    int height = get_screen_height();
    int bpp = VBE_mode_info->bpp / 8;
    int pitch = VBE_mode_info->pitch;

    if (color == 0x000000) {
        memset(framebuffer, 0, height * pitch);
    } else {
        for (int y = 0; y < height; y++) {
            uint8_t *row = framebuffer + y * pitch;
            for (int x = 0; x < width; x++) {
                int dst = x * bpp;
                row[dst]     = (color) & 0xFF;
                row[dst + 1] = (color >> 8) & 0xFF;
                row[dst + 2] = (color >> 16) & 0xFF;
            }
        }
    }
}

void clear_screen(uint32_t color) {
    clear_framebuffer(color);
    y = 0;
    x = 0;
    lines = 0;
    update_cursor_position(0, 0);
    draw_cursor();
}


void changeFontSize() {
    erase_cursor();
    if (font_mode == 0) {
        // normal -> grande
        fontWidth  = DEFAULT_SIZE * 2;
        fontHeight = DEFAULT_SIZE * 2;
        font_mode = 1;
    } else if (font_mode == 1) {
        // grande -> pequeño
        fontWidth  = (DEFAULT_SIZE / 2) > 0 ? (DEFAULT_SIZE / 2) : 1;
        fontHeight = (DEFAULT_SIZE / 2) > 0 ? (DEFAULT_SIZE / 2) : 1;
        font_mode = 2;
    } else {
        // pequeño -> normal
        fontWidth  = DEFAULT_SIZE;
        fontHeight = DEFAULT_SIZE;
        font_mode = 0;
    }
    
    draw_cursor();
}

void scroll_screen(uint32_t bg_color) {
    uint8_t * framebuffer = (uint8_t *) VBE_mode_info->framebuffer;
    int width = get_screen_width();
    int height = get_screen_height();
    int bpp = VBE_mode_info->bpp / 8;
    int pitch = VBE_mode_info->pitch;
    int scroll_rows = fontHeight * font_size * SCROLL_LINES;

    memmove(
        framebuffer,
        framebuffer + scroll_rows * pitch,
        (height - scroll_rows) * pitch
    );

    if (bg_color == 0x000000) {
        memset(framebuffer + (height - scroll_rows) * pitch, 0, scroll_rows * pitch);
    } else {
        for (int y = height - scroll_rows; y < height; y++) {
            uint8_t *row = framebuffer + y * pitch;
            for (int x = 0; x < width; x++) {
                int dst = x * bpp;
                row[dst]     = (bg_color) & 0xFF;
                row[dst + 1] = (bg_color >> 8) & 0xFF;
                row[dst + 2] = (bg_color >> 16) & 0xFF;
            }
        }
    }
}

void new_line(void) {
    y += fontHeight * font_size;
    x = 0;
    if (y + fontHeight > get_screen_height()) {
        scroll_screen(0x000000); // Fondo negro
        y -= fontHeight * font_size * SCROLL_LINES;
        if (y < 0) y = 0; // Asegurar que y no sea negativo
    }
    update_cursor_position(x, y);
}

void printString(const char *str, uint32_t color) {
    for (int i = 0; str[i] != 0; i++) {
        draw_char(str[i], color);
    }
}

void printHex(uint64_t value, uint32_t color) {
    char hex[17] = "0123456789ABCDEF";
    char buffer[17];
    buffer[16] = 0;
    for (int i = 15; i >= 0; i--) {
        buffer[i] = hex[value & 0xF];
        value >>= 4;
    }
    printString("0x", color);
    printString(buffer, color);
}


void set_text_color(uint32_t color) {
    current_color = color;
}

uint32_t get_text_color() {
    return current_color;
}

void draw_filled_box(int x, int y, int width, int height, uint32_t color) {
    for (int i = 0; i < width; i++) {
        for (int j = 0; j < height; j++) {
            putPixel(color, x + i, y + j);
        }
    }
}

void draw_cursor() {
    // Solo dibujar el cursor si está marcado como visible
    if (!cursor_visible) return;
    // Usar el color de texto actual como color del cursor (para "seguir" al prompt)
    const uint32_t cursor_color = get_text_color();
    draw_filled_box(cursor_x, cursor_y, cursor_pixel_width(), cursor_pixel_height(), cursor_color);
}

void update_cursor_position(int nx, int ny) {
    cursor_x = nx; cursor_y = ny;
}

// Permitir controlar la visibilidad del cursor desde userland
void set_cursor_visible() {
    if (!cursor_visible) {
        cursor_visible = 1;
        draw_cursor();
    } else {
        cursor_visible = 0;
        erase_cursor();
    }
}

